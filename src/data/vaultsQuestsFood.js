function formatPotionPt(en) {
  if (DIRECT_POTION_PT[en]) return DIRECT_POTION_PT[en];
  let m;
  if ((m = en.match(/^Weak Focused (\w+) Potion$/))) {
    return `Poção de ${POTION_SKILL_PT[m[1]] || m[1]} Focada Fraca`;
  }
  if ((m = en.match(/^Lesser Focused (\w+) Potion$/))) {
    return `Poção de ${POTION_SKILL_PT[m[1]] || m[1]} Focada Inferior`;
  }
  if ((m = en.match(/^Super Focused (\w+) Potion$/))) {
    return `Poção Super ${POTION_SKILL_PT[m[1]] || m[1]} Focada`;
  }
  if ((m = en.match(/^Focused (\w+) Potion$/))) {
    return `Poção de ${POTION_SKILL_PT[m[1]] || m[1]} Focada`;
  }
  if ((m = en.match(/^Weak (\w+) Potion$/))) {
    return `Poção de ${POTION_SKILL_PT[m[1]] || m[1]} Fraca`;
  }
  if ((m = en.match(/^Lesser (\w+) Potion$/))) {
    return `Poção de ${POTION_SKILL_PT[m[1]] || m[1]} Inferior`;
  }
  if ((m = en.match(/^Super (\w+) Potion$/))) {
    return `Poção Super ${POTION_SKILL_PT[m[1]] || m[1]}`;
  }
  if ((m = en.match(/^(\w+) Potion$/))) {
    return `Poção de ${POTION_SKILL_PT[m[1]] || m[1]}`;
  }
  return en;
}

