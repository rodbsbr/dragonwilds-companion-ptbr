const WIKI_ITEMS_MAP = Object.fromEntries(((wikiData && wikiData.items) || []).map((i) => [i.n, i]));

const ALL_POTIONS_LIST = ((wikiData && wikiData.items) || [])
  .filter((i) => i.c === 'pocao')
  .sort((a, b) => {
    const orderA = POTION_ORDER[a.n] || 100;
    const orderB = POTION_ORDER[b.n] || 100;
    if (orderA !== orderB) return orderA - orderB;
    return a.n.localeCompare(b.n);
  })
  .map((item) => {
    const ptTitle = formatPotionPt(item.n);
    const rec = item.r?.[0];
    const isImbuing = rec?.f === 'Imbuing Barrel';
    const station = isImbuing ? 'Barril de Imbuir (Imbuing Barrel)' : 'Caldeirão de Poções (Brewing Cauldron)';
    const type = isImbuing ? 'Poção (Barril de Imbuir)' : 'Poção (Caldeirão)';
    const subCat = getPotionSubCat(item.n);

    const ingredientsList = (rec?.m || []).map(([ingName, qty]) => {
      const meta = INGREDIENT_META[ingName] || RAW_INFO[ingName];
      if (meta) {
        return {
          name: meta.pt || CUSTOM_PT_NAMES[ingName] || ingName,
          rawName: ingName,
          qty,
          where: meta.where,
          toolReq: meta.toolReq || '',
          mapLayerId: meta.mapLayerId || meta.mapLayer,
        };
      }
      const otherItem = WIKI_ITEMS_MAP[ingName];
      return {
        name: CUSTOM_PT_NAMES[ingName] || formatPotionPt(ingName),
        rawName: ingName,
        qty,
        where: otherItem?.r?.[0]?.f ? `Feito em: ${otherItem.r[0].f}` : (otherItem?.d || 'Encontrado explorando Ashenfall'),
        toolReq: '',
      };
    });

    const perks = item.n.includes('Antipoison')
      ? ['Fungal Fortitude']
      : item.n.includes('Stamina') || item.n.includes('Agility')
      ? ['Sugar Rush']
      : item.n.includes('Mining') || item.n.includes('Woodcutting') || item.n.includes('Lumberjack') || item.n.includes('Quarrymaster')
      ? ["Foreman's Feast"]
      : [];

    let hp = 'Buff Alquímico';
    if (item.n.includes('Healing')) hp = 'Recupera Vida';
    else if (item.n.includes('Antipoison')) hp = 'Imunidade a Veneno';
    else if (item.n.includes('Antifire')) hp = 'Resistência a Fogo';
    else if (item.n.includes('Attack')) hp = 'Bônus de Ataque';

    return {
      id: `w:${item.n}`,
      recipeId: `w:${item.n}`,
      name: `${ptTitle} (${item.n})`,
      category: 'pocao',
      potionSubCat: subCat,
      type,
      station,
      hp,
      sustenance: 'Bebida Alquímica',
      weight: (item.w || '1.0') + ' kg',
      duration: item.n.startsWith('Weak') ? 'Curta' : item.n.startsWith('Lesser') ? 'Média' : item.n.startsWith('Super') ? 'Muito Longa' : 'Longa',
      perks,
      ingredients: (rec?.m || []).map(([name, qty]) => `${qty}x ${INGREDIENT_META[name]?.pt || name}`).join(' + '),
      ingredientsList,
      imageFile: item.img || 'Antipoison_Potion.png',
      tip: getPotionTip(item.n, item.d),
    };
  });

