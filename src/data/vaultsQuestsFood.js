function getPotionSubCat(name) {
  if (name.includes('Antipoison')) return 'antiveneno';
  if (name.includes('Antifire')) return 'antifogo';
  if (name.includes('Healing')) return 'cura';
  if (name.includes('Attack') || name.includes('Magic') || name.includes('Weapon Poison')) return 'combate';
  if (name.includes('Mining') || name.includes('Quarrymaster') || name.includes('Lumberjack') || name.includes('Woodcutting')) return 'coleta';
  if (name.includes('Agility') || name.includes('Stamina')) return 'mobilidade';
  return 'habilidade';
}

